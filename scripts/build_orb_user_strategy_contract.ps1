$ErrorActionPreference='Stop'
$root=Split-Path -Parent $PSScriptRoot
$dir=Join-Path $root 'IndicatorCodeExamples'
$main=[IO.File]::ReadAllText((Join-Path $dir 'OrbUltimateEA_StrategyLibrary.mq5'))
$library=[IO.File]::ReadAllText((Join-Path $dir 'OrbStrategyPresetLibrary.mqh'))
$struct=[regex]::Match($library,'(?s)struct OrbStrategyPreset\s*\{(.*?)bool metric1yReady').Groups[1].Value
$fields=@([regex]::Matches($struct,'(?m)^\s+(\w+)\s+(\w+);') | ForEach-Object {@{type=$_.Groups[1].Value;name=$_.Groups[2].Value}})
if($fields.Count -lt 50){throw 'Preset schema extraction failed'}
$runtimes=@([regex]::Matches($main,'(?m)^(\w+)\s+(g_rt\w+)\s*=') | Where-Object {$_.Groups[2].Value -notin @('g_rtHistoricalWeeks','g_rtEaEnabled','g_rtRiskPerTradePct','g_rtAdvancedAuditEngine')} | ForEach-Object {@{type=$_.Groups[1].Value;name=$_.Groups[2].Value}})
foreach($name in @('g_btFillMode','g_btSameBarPolicy','g_btNativeParity','g_btSpreadPts','g_btSlippagePts','g_btCommissionPerLot')){
    $m=[regex]::Match($main,'(?m)^(\w+)\s+'+$name+'\s*=');if(!$m.Success){throw 'Missing runtime '+$name}
    $runtimes+=@{type=$m.Groups[1].Value;name=$name}
}
$body=[regex]::Match($main,'(?s)void OrbStrategyPresetApplyValues\(.*?bool OrbStrategyPresetMatchesRuntime').Value
$map=@{}
foreach($m in [regex]::Matches($body,'(g_rt\w+)\s*=([^;]+);')){
    $p=[regex]::Match($m.Groups[2].Value,'p\.(\w+)')
    if($p.Success -and !$map.ContainsKey($p.Groups[1].Value)){$map[$p.Groups[1].Value]=$m.Groups[1].Value}
}
$map['rfMaster']='g_orbRfEnabled'
for($i=0;$i -lt 6;$i++){$map['regime'+$i]='g_regimeAllowed['+$i+']'}
for($i=0;$i -lt 12;$i++){$map[('rf{0:d2}' -f ($i+1))]='g_orbRfBlocked['+$i+']'}
$schema=(@($fields+$runtimes | ForEach-Object {$_.type+':'+$_.name}) -join ';')
$sha=[Security.Cryptography.SHA256]::Create()
$hash=([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($schema)))).Replace('-','').ToLowerInvariant();$sha.Dispose()
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/build_orb_user_strategy_contract.ps1. Do not hand edit.')
$lines.Add('#define ORB_CUSTOM_SCHEMA "'+$hash+'"')
$lines.Add('#define ORB_CUSTOM_PRESET_TOKENS '+$fields.Count)
$lines.Add('#define ORB_CUSTOM_RUNTIME_TOKENS '+$runtimes.Count)
$lines.Add('string OrbCustomInputSignature(){string value="";')
$excluded='^Inp(?:Dashboard|ShowDashboard|HistoricalDays$|HistoricalWeeks$|HistoricalAuditVerboseLog$|DrawHistorical|Audit|Log|Validation|Tester|EaEnabled$|Magic$|Risk|Lots|FixedLot|Ftmo|FTMO)'
foreach($m in [regex]::Matches($main,'(?m)^input\s+(\w+)\s+(Inp\w+)\s*=')){
    $name=$m.Groups[2].Value;if($name -match $excluded){continue}
    $expr=if($m.Groups[1].Value -eq 'double'){'DoubleToString('+$name+',16)'}else{'(string)'+$name}
    $lines.Add('   value+="'+$name+':"+(string)StringLen('+ $expr +')+":"+'+$expr+'+";";')
    if($name -eq 'InpSignalTimeframe'){
        $lines.Add('   value+="InpBrokerGmtOffsetHours:"+(string)StringLen(DoubleToString(OrbBrokerOffsetHours(),16))+":"+DoubleToString(OrbBrokerOffsetHours(),16)+";";')
    }
}
$lines.Add('   return OrbMlSha256(value);}')
$lines.Add('void OrbCustomCapturePreset(OrbStrategyPreset &p){OrbPresetDefaults(p);')
foreach($field in $fields){
    if($field.type -eq 'string' -or $field.name -eq 'family'){continue}
    if(!$map.ContainsKey($field.name)){throw ('No runtime mapping: '+$field.name)}
    $lines.Add('   p.'+$field.name+'='+$map[$field.name]+';')
}
$lines.Add('}')
foreach($kind in @('Preset','Runtime')){
    $vars=if($kind -eq 'Preset'){$fields}else{$runtimes}
    $param=if($kind -eq 'Preset'){'const OrbStrategyPreset &p'}else{''}
    $lines.Add('string OrbCustom'+$kind+'Dump('+$param+'){string out="";')
    foreach($v in $vars){$name=if($kind -eq 'Preset'){'p.'+$v.name}else{$v.name};$expr=if($v.type -eq 'double'){'DoubleToString('+$name+',16)'}elseif($v.type -eq 'bool'){'('+$name+'?"1":"0")'}else{'(string)'+$name};$lines.Add('   out+='+$expr+'+"\n";')}
    $lines.Add('   return out;}')
    $args=if($kind -eq 'Preset'){'OrbStrategyPreset &p'}else{'bool apply'}
    $lines.Add('bool OrbCustom'+$kind+'Read(const string &v[],int start,'+$args+'){')
    $lines.Add('   if(ArraySize(v)<start+'+$vars.Count+')return false;double n['+$vars.Count+'];')
    for($i=0;$i -lt $vars.Count;$i++){
        $v=$vars[$i];if($v.type -eq 'string'){continue}
        $guard=if($v.type -eq 'bool'){'||(n['+$i+']!=0&&n['+$i+']!=1)'}elseif($v.type -ne 'double'){'||n['+$i+']!=MathFloor(n['+$i+'])||MathAbs(n['+$i+'])>2147483647'}else{''}
        $lines.Add('   if(!OrbMlNumber(v[start+'+$i+'],n['+$i+'])'+$guard+')return false;')
    }
    if($kind -eq 'Runtime'){$lines.Add('   if(!apply)return true;')}
    for($i=0;$i -lt $vars.Count;$i++){
        $v=$vars[$i];$name=if($kind -eq 'Preset'){'p.'+$v.name}else{$v.name}
        $rhs=if($v.type -eq 'string'){'v[start+'+$i+']'}else{'('+$v.type+')n['+$i+']'}
        $lines.Add('   '+$name+'='+$rhs+';')
    }
    $lines.Add('   return true;}')
}
[IO.File]::WriteAllText((Join-Path $dir 'OrbStrategyUserContract.mqh'),($lines -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
Write-Output ('User strategy contract: '+$fields.Count+' preset fields; '+$runtimes.Count+' runtime fields; '+$hash)
