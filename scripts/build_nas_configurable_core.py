"""Generate a library-only period adapter; leave the shared NAS core untouched."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INC = ROOT / 'IndicatorCodeExamples'

def generate():
    original = (INC / 'NasUltimate_Core.mqh').read_text(encoding='utf-8-sig')
    body = original[original.index('int NAS_Calculate('):]
    body = body.replace('int NAS_Calculate(', 'int NAS_LibraryCalculate(')
    body = body.replace('   if(n <= 0)', '''   if(InpNasSmaFastPeriod<1 || InpNasSmaFastPeriod>1000
      || InpNasSmaMidPeriod<1 || InpNasSmaMidPeriod>1000
      || InpNasSignalSmaPeriod<1 || InpNasSignalSmaPeriod>1000
      || InpNasSuperTrendAtrPeriod<1 || InpNasSuperTrendAtrPeriod>1000)
   {ArrayFree(out);return 0;}
   if(n <= 0)''', 1)
    body = body.replace('NAS_WilderATR(rates, n, 11, atr11)', 'NAS_WilderATR(rates, n, InpNasSuperTrendAtrPeriod, atr11)')
    for old, new in ((8, 'InpNasSmaFastPeriod'), (9, 'InpNasSmaMidPeriod'), (13, 'InpNasSignalSmaPeriod')):
        body = body.replace(f'NAS_SMA(closeArr, i, {old})', f'NAS_SMA(closeArr, i, {new})')
    (INC / 'NasStrategyConfigurableCore.mqh').write_text(
        '// Generated by scripts/build_nas_configurable_core.py. Default math equals NasUltimate_Core.mqh.\n'
        '#ifndef NAS_STRATEGY_CONFIGURABLE_CORE_MQH\n#define NAS_STRATEGY_CONFIGURABLE_CORE_MQH\n'
        + body + '\n#endif\n', encoding='ascii')

if __name__ == '__main__':
    generate()
