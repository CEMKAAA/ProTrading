$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'IndicatorCodeExamples'
$main = [IO.File]::ReadAllText((Join-Path $dir 'OrbUltimateEA_StrategyLibrary.mq5'))
$files = @('OrbUltimateEA_StrategyLibrary.mq5', 'OrbStrategyMLCore.mqh', 'OrbStrategyMLPipeline.mqh', 'OrbStrategyMLJobs.mqh',
    'OrbStrategyPresetLibrary.mqh', 'OrbStrategyUserLibrary.mqh', 'OrbStrategyUserContract.mqh', 'NasUltimate_Core.mqh', 'LiqNarrativeSol_RegimeV3.mqh',
    'OrbAdvancedAuditEngine.mqh', 'OrbUltimate_ProfessionalPipeline.mqh')
$provenance = ($files | ForEach-Object {
    $text = [IO.File]::ReadAllText((Join-Path $dir $_)).Replace("`r`n", "`n")
    $_ + ':' + $text
}) -join "`n"
$sha = [Security.Cryptography.SHA256]::Create()
$digest = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($provenance)))).Replace('-', '').ToLowerInvariant()
$sha.Dispose()
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/build_orb_ml_contract.ps1; regenerate after source changes.')
$lines.Add('#define ORB_ML_SOURCE "' + $digest + '"')
$lines.Add('string OrbMlConfiguration()')
$lines.Add('{')
$lines.Add('   string value=ORB_ML_SOURCE;')
$lines.Add('   OrbMlConfigField(value,"compiled_at",(string)__DATETIME__);')
$lines.Add('   OrbMlConfigField(value,"symbol",_Symbol);')
$lines.Add('   OrbMlConfigField(value,"broker",AccountInfoString(ACCOUNT_SERVER));')
$lines.Add('   OrbMlConfigField(value,"chart_tf",(string)(int)_Period);')
$lines.Add('   OrbMlConfigField(value,"point",DoubleToString(_Point,16));')
$lines.Add('   OrbMlConfigField(value,"tick_size",DoubleToString(SymbolInfoDouble(_Symbol,SYMBOL_TRADE_TICK_SIZE),16));')
$lines.Add('   OrbMlConfigField(value,"digits",(string)_Digits);')
# Exclude UI, ownership, money sizing and audit-window selection. Retain costs,
# strategy defaults and all strategy runtime values (conservative binding).
$excluded = '^Inp(?:Dashboard|ShowDashboard|HistoricalDays$|HistoricalWeeks$|HistoricalAuditVerboseLog$|DrawHistorical|Audit|Log|Validation|Tester|EaEnabled$|Magic$|Risk|Lots|FixedLot|Ftmo|FTMO)'
$inputs = [regex]::Matches($main, '(?m)^input\s+(\w+)\s+(Inp\w+)\s*=')
foreach ($m in $inputs) {
    $name = $m.Groups[2].Value
    if ($name -match $excluded) { continue }
    $expr = if ($m.Groups[1].Value -eq 'double') { "DoubleToString($name,16)" } else { "(string)$name" }
    $lines.Add('   OrbMlConfigField(value,"' + $name + '",' + $expr + ');')
}
$runtime = [regex]::Matches($main, '(?m)^(\w+)\s+(g_rt\w+)\s*=')
foreach ($m in $runtime) {
    $name = $m.Groups[2].Value
    if ($name -in @('g_rtHistoricalWeeks', 'g_rtEaEnabled', 'g_rtRiskPerTradePct')) { continue }
    $expr = if ($m.Groups[1].Value -eq 'double') { "DoubleToString($name,16)" } else { "(string)$name" }
    $lines.Add('   OrbMlConfigField(value,"' + $name + '",' + $expr + ');')
}
$lines.Add('   OrbMlConfigField(value,"rf_master",(string)g_orbRfEnabled);')
$lines.Add('   OrbMlConfigField(value,"sim_fill",(string)g_btFillMode);')
$lines.Add('   OrbMlConfigField(value,"sim_same_bar",(string)g_btSameBarPolicy);')
$lines.Add('   OrbMlConfigField(value,"sim_native_parity",(string)g_btNativeParity);')
$lines.Add('   OrbMlConfigField(value,"sim_spread",DoubleToString(g_btSpreadPts,16));')
$lines.Add('   OrbMlConfigField(value,"sim_slippage",DoubleToString(g_btSlippagePts,16));')
$lines.Add('   OrbMlConfigField(value,"sim_commission",DoubleToString(g_btCommissionPerLot,16));')
$lines.Add('   for(int i=0;i<ORB_REGIME_COUNT;i++)OrbMlConfigField(value,"reg"+(string)i,(string)g_regimeAllowed[i]);')
$lines.Add('   for(int i=0;i<ORB_RF_COUNT;i++)OrbMlConfigField(value,"rf"+(string)i,(string)g_orbRfBlocked[i]);')
$lines.Add('   OrbStrategyPreset p;')
$lines.Add('   if(!OrbStrategyPresetLoad(g_strategyPresetIndex,p))return "";')
$lines.Add('   OrbMlConfigField(value,"preset",p.id);')
$lines.Add('   return OrbMlSha256(value);')
$lines.Add('}')
[IO.File]::WriteAllText((Join-Path $dir 'OrbStrategyMLConfig.mqh'), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Output "ML source contract: $digest"
