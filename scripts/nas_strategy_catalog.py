def catalogue():
    result=[]
    for image,symbol,start,end,pips,rr,scale,reverse,volume in REVIEWED:
        path=IMAGE_ROOT/image
        settings=dict(symbol=symbol,tf_minutes=5,start=start,end=end,pip_sl=pips,
            target_r=rr,sl_scale_pct=scale,atr_buffer=.2,window_reverse=reverse,
            volume_on=volume is not None,volume_multiplier=volume or 1,
            hold='',duplicate_on=True,regime_filter=False,macro_mask=63,
            geometry=2,hcbe=0,invert=False,invert_r=0)
        result.append(dict(id='nas_'+hashlib.sha256(image.encode()).hexdigest()[:16],
            name=path.stem,image=image,image_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
            settings=settings,review='visible_dashboard_only',
            assumptions=['Hidden inputs use current NAS defaults; not recoverable from PNG.',
                'Absent VOL and WIN REV controls use OFF; absent hold uses OFF.',
                'Risk, capital, daily guards, PUB/ONLY/NAT and account identity are never imported.'],
            notes=['Filename says H1 but screenshot explicitly displays PERIOD_M5.'] if 'H1Model' in image else [],
            metrics=None))
    return result

def generate():
    records=catalogue()
    output=ROOT/'data/nas_strategy_library'
    output.mkdir(parents=True,exist_ok=True)
    (output/'catalog.json').write_text(json.dumps(dict(version=1,strategies=records),indent=2),encoding='utf-8')
    lines=['// Generated by scripts/nas_strategy_catalog.py; do not edit.',
           'void NasLibraryLoadBuiltins()', '{']
    for r in records:
        s=r['settings']
        lines.append('   NasLibraryAddBuiltin("%s","%s","%s",%d,"%s","%s",%.8f,%.8f,%.8f,%s,%s,%.8f);' %
            (r['id'],r['name'],s['symbol'],s['tf_minutes'],s['start'],s['end'],s['pip_sl'],s['target_r'],s['sl_scale_pct'],
             str(s['window_reverse']).lower(),str(s['volume_on']).lower(),s['volume_multiplier']))
    lines+=['}','']
    (ROOT/'IndicatorCodeExamples/NasStrategyPresets.mqh').write_text('\n'.join(lines),encoding='ascii')
    return len(records)

